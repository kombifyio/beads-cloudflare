// The Worker speaks JSON, so the store converts between wire maps and the Beads
// domain types here. Keeping the conversion in one place is what makes the
// profile's fidelity checkable: every field the store does not emit is absent
// rather than zero-filled with a value it did not actually hold.

func strOf(v any) string {
	if s, ok := v.(string); ok {
		return s
	}
	return ""
}

func timeOf(v any) time.Time {
	s := strOf(v)
	if s == "" {
		return time.Time{}
	}
	parsed, err := time.Parse(time.RFC3339Nano, s)
	if err != nil {
		return time.Time{}
	}
	return parsed
}

func derefString(s *string) string {
	if s == nil {
		return ""
	}
	return *s
}

func pickActor(asserted, fallback string) string {
	if asserted != "" {
		return asserted
	}
	return fallback
}

// issueFromMap converts one wire issue into the domain type.
func memoriesFromMap(raw map[string]any) map[string]string {
	out := map[string]string{}
	for key, value := range raw {
		if key == "items" {
			if items, ok := value.([]any); ok {
				for _, item := range items {
					m, ok := item.(map[string]any)
					if !ok {
						continue
					}
					out[strOf(m["key"])] = strOf(m["value"])
				}
			}
			continue
		}
		if s, ok := value.(string); ok {
			out[key] = s
		}
	}
	return out
}

// Unsupported lists every method this backend answers with ErrUnsupported,
// together with why. The conformance suite walks it.
func Unsupported() map[string]string {
	out := map[string]string{}
	for method, reason := range unsupportedMethods {
		out[method] = reason
	}
	return out
}

var unsupportedMethods = map[string]string{}

func init() {
	for method, reason := range vcUnsupported {
		unsupportedMethods[method] = reason
	}
	for method, reason := range coreUnsupported {
		unsupportedMethods[method] = reason
	}
}

// The two allowlists below are generated by cmd/genstubs and embedded rather
// than hand-maintained: a method that refuses at runtime but is absent from the
// allowlist is a method the conformance suite never checks, and that drift is
// exactly what this file exists to prevent.

//go:embed allowlist_versioncontrol.txt
var versionControlList string

//go:embed allowlist_profile.txt
var profileList string

const (
	reasonVersionControl = "the Cloudflare store serves the tracker over HTTPS; it has no version-control, history, remote, sync, federation, compaction or fast-statistics surface"
	reasonNotInProfile   = "the /v0 profile served by kombifyio/beads-cloudflare does not implement this operation"
)

// parseAllowlist reads the generated "name": "reason" lines.
func parseAllowlist(text, reason string) map[string]string {
	out := map[string]string{}
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		name, _, _ := strings.Cut(line, ":")
		out[strings.Trim(strings.TrimSpace(name), `"`)] = reason
	}
	return out
}

var (
	vcUnsupported   = parseAllowlist(versionControlList, reasonVersionControl)
	coreUnsupported = parseAllowlist(profileList, reasonNotInProfile)
)

// MaxTrackerID is the tracker's id length limit, from the server's own isTrackerId.
// An id past it matches no route, so a client that builds one must fold it first.
const MaxTrackerID = 40

// NormalizeTracker folds a repository name into a tracker id. A tracker id has
// to match [a-z0-9]+(-[a-z0-9]+)*, and repository names are mixed case, so
// "Acme-WebApp" would match no route at all.
func NormalizeTracker(name string) (string, error) {
	// Every run of characters outside [a-z0-9] becomes one dash, including
	// underscores and spaces, so Acme_Blog and "Acme Blog" both reach
	// acme-blog rather than losing their word boundary.
	var b strings.Builder
	pendingDash := false
	for _, r := range strings.ToLower(name) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			if pendingDash && b.Len() > 0 {
				b.WriteRune('-')
			}
			pendingDash = false
			b.WriteRune(r)
			continue
		}
		pendingDash = true
	}
	folded := b.String()
	if folded == "" {
		return "", fmt.Errorf("cloudflare backend: %q does not reduce to a tracker id", name)
	}
	if len(folded) > MaxTrackerID {
		return "", fmt.Errorf("cloudflare backend: tracker id %q is %d characters, over the %d limit", folded, len(folded), MaxTrackerID)
	}
	return folded, nil
}

// mapsIn normalizes a decoded JSON array of objects into []map[string]any, which
// is what the wire helpers consume. A missing or null member is an empty list.
func mapsIn(v any) []map[string]any {
	items, ok := v.([]any)
	if !ok {
		return nil
	}
	out := make([]map[string]any, 0, len(items))
	for _, item := range items {
		if m, ok := item.(map[string]any); ok {
			out = append(out, m)
		}
	}
	return out
}
